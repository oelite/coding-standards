#!/usr/bin/env python3
"""Generate native OpenCode and Claude agent definitions from canonical roles.

Usage:
    python3 scripts/generate-role-agents.py --target-root /path/to/repo
    python3 scripts/generate-role-agents.py --target-root /path/to/repo --check
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


HOST_DIRECTORIES = {
    "opencode": (".opencode", "agents"),
    "claude": (".claude", "agents"),
}
CANONICAL_ROLE_FILENAMES = frozenset(
    {
        "daniel.md", "emma.md", "ethan.md", "felix.md", "grace.md", "isabella.md",
        "jonathan.md", "marcus.md", "maya.md", "olivia.md", "sophia.md", "victor.md",
    }
)


def role_files(source_root: Path) -> list[Path]:
    roles_dir = source_root / "agents" / "roles"
    if not roles_dir.is_dir():
        raise FileNotFoundError(f"Canonical roles directory not found: {roles_dir}")
    files = sorted(path for path in roles_dir.glob("*.md") if path.is_file())
    if not files:
        raise FileNotFoundError(f"No canonical role markdown files found in {roles_dir}")
    if roles_dir.resolve() == (Path(__file__).resolve().parent.parent / "agents" / "roles").resolve():
        actual = {path.name for path in files}
        missing = CANONICAL_ROLE_FILENAMES - actual
        unexpected = actual - CANONICAL_ROLE_FILENAMES
        if missing or unexpected:
            details = []
            if missing:
                details.append(f"missing roles: {', '.join(sorted(missing))}")
            if unexpected:
                details.append(f"unexpected roles: {', '.join(sorted(unexpected))}")
            raise ValueError(f"Canonical role coverage is incomplete in {roles_dir}: {'; '.join(details)}")
    return files


def role_description(source: str, role_name: str) -> str:
    for line in source.splitlines():
        heading = re.match(r"^#\s+Role:\s*(.+?)\s*[—-]\s*(.+?)\s*$", line)
        if heading:
            return f"{heading.group(1)}: {heading.group(2)}"
    return f"{role_name.title()} role agent"


def quote_yaml(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render(role_file: Path, source_root: Path, host: str) -> str:
    source = role_file.read_text(encoding="utf-8")
    role_name = role_file.stem
    description = role_description(source, role_name)
    relative_source = role_file.relative_to(source_root).as_posix()

    lines = ["---", f"description: {quote_yaml(description)}"]
    if host == "opencode":
        lines.append("mode: subagent")
    lines.extend(["---", f"<!-- Generated from {relative_source}; do not edit this file directly. -->", ""])
    return "\n".join(lines) + source


def generated_files(source_root: Path) -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for role_file in role_files(source_root):
        for host, parts in HOST_DIRECTORIES.items():
            outputs[Path(*parts, f"{role_file.stem}.md")] = render(role_file, source_root, host)
    return outputs


def validate_destinations(target_root: Path, outputs: dict[Path, str]) -> None:
    if target_root.is_symlink():
        raise ValueError(f"Refusing symlinked target root: {target_root}")
    resolved_root = target_root.resolve()
    for relative_path in outputs:
        destination = target_root / relative_path
        current = target_root
        for part in relative_path.parts:
            current = current / part
            if current.is_symlink():
                raise ValueError(f"Refusing symlinked output path: {current}")
        resolved_destination = destination.resolve()
        if not resolved_destination.is_relative_to(resolved_root):
            raise ValueError(f"Output destination escapes target root: {destination}")


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-root",
        "--source",
        "--standards-root",
        dest="source_root",
        type=Path,
        default=None,
        help="coding-standards root containing agents/roles (default: inferred from script location)",
    )
    parser.add_argument(
        "--target-root",
        "--target",
        "--repo",
        "--out-root",
        "--output-root",
        dest="target_root",
        type=Path,
        default=None,
        help="repository root receiving generated agent definitions",
    )
    parser.add_argument(
        "positional_target",
        nargs="?",
        type=Path,
        help="repository root receiving generated agent definitions (positional)",
    )
    parser.add_argument(
        "--check",
        "--verify",
        "--dry-run",
        dest="check",
        action="store_true",
        help="report missing or stale generated files without writing",
    )
    args = parser.parse_args(argv)
    if args.source_root is None:
        args.source_root = Path(__file__).resolve().parent.parent
    if args.target_root is None:
        args.target_root = args.positional_target
    if args.target_root is None:
        parser.error("--target-root (or positional target root) is required")
    return args


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    source_root = args.source_root.resolve()
    target_root = args.target_root.absolute()
    try:
        outputs = generated_files(source_root)
        validate_destinations(target_root, outputs)
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    differences: list[Path] = []
    for relative_path, expected in outputs.items():
        destination = target_root / relative_path
        if not destination.is_file() or destination.read_text(encoding="utf-8") != expected:
            differences.append(destination)

    if args.check:
        if differences:
            print("Generated role-agent definitions are missing or stale:")
            for path in differences:
                print(f"  {path}")
            print("Run the generator without --check to update them.")
            return 1
        print(f"All {len(outputs)} role-agent definitions are current under {target_root}.")
        return 0

    for relative_path, content in outputs.items():
        destination = target_root / relative_path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(content.encode("utf-8"))
    print(f"Generated {len(outputs)} role-agent definitions under {target_root}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

